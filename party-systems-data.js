  function toRoman(num) {
    const n = Math.max(1, Math.floor(Number(num) || 7));
    const map = [
      [50, 'L'], [40, 'XL'], [10, 'X'], [9, 'IX'], [5, 'V'], [4, 'IV'], [1, 'I'],
    ];
    let rem = n;
    let out = '';
    for (const [val, sym] of map) {
      while (rem >= val) {
        out += sym;
        rem -= val;
      }
    }
    return out;
  }

