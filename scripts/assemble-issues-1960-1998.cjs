/**
 * scripts/assemble-issues-1960-1998.cjs
 * Assembles and verifies all 5 brackets for 1960-1998.
 * Exports:
 *   - HISTORICAL_ISSUES_1960_1998.csv
 *   - historical-issues-1960-1998-data.js
 *   - HISTORICAL_ISSUES_MASTER_1960_2026.csv (combined 1960-2026)
 *   - historical-issues-master-data.js (combined 1960-2026)
 */

const fs = require('fs');
const path = require('path');

const bA = require('./build-issues-1960-1966.cjs');
const bB = require('./build-issues-1968-1974.cjs');
const bC = require('./build-issues-1976-1982.cjs');
const bD = require('./build-issues-1984-1990.cjs');
const bE = require('./build-issues-1992-1998.cjs');

console.log('Bracket A (1960-1966):', bA.length);
console.log('Bracket B (1968-1974):', bB.length);
console.log('Bracket C (1976-1982):', bC.length);
console.log('Bracket D (1984-1990):', bD.length);
console.log('Bracket E (1992-1998):', bE.length);

const all1960_1998 = [...bA, ...bB, ...bC, ...bD, ...bE];
console.log('Total 1960-1998 issues:', all1960_1998.length);

// Validation
const seenIds = new Set();
const cycleCounts = {};
const validTypes = new Set(['Ideological', 'News']);
const validParties = ['dem', 'gop', 'lib', 'grn', 'con', 'soc'];

all1960_1998.forEach((issue, index) => {
  if (!issue.cycle || typeof issue.cycle !== 'number') {
    throw new Error('Issue at index ' + index + ' missing valid cycle: ' + JSON.stringify(issue));
  }
  if (!issue.id || typeof issue.id !== 'string') {
    throw new Error('Issue at index ' + index + ' missing valid id: ' + JSON.stringify(issue));
  }
  if (seenIds.has(issue.id)) {
    throw new Error('Duplicate issue id detected: ' + issue.id);
  }
  seenIds.add(issue.id);

  cycleCounts[issue.cycle] = (cycleCounts[issue.cycle] || 0) + 1;

  if (!validTypes.has(issue.type)) {
    throw new Error('Issue ' + issue.id + ' has invalid type: ' + issue.type);
  }
  if (typeof issue.tier !== 'number' || issue.tier < 1 || issue.tier > 10) {
    throw new Error('Issue ' + issue.id + ' has invalid tier: ' + issue.tier);
  }
  if (!issue.pole1 || !issue.pole10) {
    throw new Error('Issue ' + issue.id + ' missing poles: pole1=' + issue.pole1 + ', pole10=' + issue.pole10);
  }
  if (!issue.stances) {
    throw new Error('Issue ' + issue.id + ' missing stances');
  }
  validParties.forEach(p => {
    const s = issue.stances[p];
    if (typeof s !== 'number' || s < 1 || s > 10) {
      throw new Error('Issue ' + issue.id + ' has invalid stance for ' + p + ': ' + s);
    }
  });
});

console.log('Validation passed for all 1960-1998 issues!');
console.log('Cycle counts 1960-1998:', cycleCounts);

// Helper for CSV escaping
function escapeCsv(val) {
  if (val === null || val === undefined) return '""';
  const str = String(val).replace(/"/g, '""');
  return '"' + str + '"';
}

// Generate CSV for 1960-1998
const csvHeader = [
  'cycle',
  'id',
  'name',
  'type',
  'era_span',
  'domain',
  'salience_tier',
  'debate_description',
  'pole_1_definition',
  'pole_10_definition',
  'stance_dem_people',
  'stance_gop_heritage',
  'stance_lib_liberty',
  'stance_grn_green',
  'stance_con_constitution',
  'stance_soc_socialist'
].join(',');

const rows1960_1998 = all1960_1998.map(i => [
  i.cycle,
  escapeCsv(i.id),
  escapeCsv(i.name),
  escapeCsv(i.type),
  escapeCsv(i.eraSpan),
  escapeCsv(i.domain),
  i.tier,
  escapeCsv(i.debate),
  escapeCsv(i.pole1),
  escapeCsv(i.pole10),
  i.stances.dem,
  i.stances.gop,
  i.stances.lib,
  i.stances.grn,
  i.stances.con,
  i.stances.soc
].join(','));

const csvContent1960_1998 = [csvHeader, ...rows1960_1998].join('\n');
const csvPath1960_1998 = path.join(__dirname, '..', 'HISTORICAL_ISSUES_1960_1998.csv');
fs.writeFileSync(csvPath1960_1998, csvContent1960_1998, 'utf8');
console.log('Wrote HISTORICAL_ISSUES_1960_1998.csv successfully.');

// Generate JS Module for 1960-1998
const jsContent1960_1998 = `/**
 * historical-issues-1960-1998-data.js
 * Historical Election Issues Dataset: 1960 through 1998 (20 cycles, 1005 issues).
 * Generated by assemble-issues-1960-1998.cjs.
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.HISTORICAL_ISSUES_1960_1998 = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  return ${JSON.stringify(all1960_1998, null, 2)};
}));
`;
const jsPath1960_1998 = path.join(__dirname, '..', 'historical-issues-1960-1998-data.js');
fs.writeFileSync(jsPath1960_1998, jsContent1960_1998, 'utf8');
console.log('Wrote historical-issues-1960-1998-data.js successfully.');

// Now load 2000-2026 dataset to build unified Master files (1960-2026)
const js2000_2026_Path = path.join(__dirname, '..', 'historical-issues-data.js');
if (fs.existsSync(js2000_2026_Path)) {
  const issues2000_2026 = require(js2000_2026_Path);
  console.log('Found 2000-2026 issues dataset:', issues2000_2026.length);

  const masterIssues = [...all1960_1998, ...issues2000_2026];
  console.log('Master combined issues count (1960-2026):', masterIssues.length);

  const masterRows = masterIssues.map(i => [
    i.cycle,
    escapeCsv(i.id),
    escapeCsv(i.name),
    escapeCsv(i.type),
    escapeCsv(i.eraSpan),
    escapeCsv(i.domain),
    i.tier,
    escapeCsv(i.debate),
    escapeCsv(i.pole1),
    escapeCsv(i.pole10),
    i.stances.dem,
    i.stances.gop,
    i.stances.lib,
    i.stances.grn,
    i.stances.con,
    i.stances.soc
  ].join(','));

  const masterCsvContent = [csvHeader, ...masterRows].join('\n');
  const masterCsvPath = path.join(__dirname, '..', 'HISTORICAL_ISSUES_MASTER_1960_2026.csv');
  fs.writeFileSync(masterCsvPath, masterCsvContent, 'utf8');
  console.log('Wrote HISTORICAL_ISSUES_MASTER_1960_2026.csv successfully.');

  const masterJsContent = `/**
 * historical-issues-master-data.js
 * Historical Election Issues Master Dataset: 1960 through 2026 (34 cycles, ${masterIssues.length} issues).
 * Generated by assemble-issues-1960-1998.cjs.
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.HISTORICAL_ISSUES_MASTER = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  return ${JSON.stringify(masterIssues, null, 2)};
}));
`;
  const masterJsPath = path.join(__dirname, '..', 'historical-issues-master-data.js');
  fs.writeFileSync(masterJsPath, masterJsContent, 'utf8');
  console.log('Wrote historical-issues-master-data.js successfully.');
}
