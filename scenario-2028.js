function v07ClampRating(val) {
  return Math.max(1, Math.min(10, Math.round(Number(val) || 5)));
}

function v07ComputeQuality(ratings) {
  if (!ratings || typeof ratings !== 'object') return 5;
  if (typeof window !== 'undefined' && window.PartyChairData && typeof window.PartyChairData.computeCandidateQuality === 'function') {
    return window.PartyChairData.computeCandidateQuality(ratings);
  }
  const sum = V07_POSITIVE_RATING_KEYS.reduce((acc, k) => acc + v07ClampRating(ratings[k] ?? 5), 0);
  const avg = sum / V07_POSITIVE_RATING_KEYS.length;
  const corruptionPenalty = Math.max(0, (v07ClampRating(ratings.corruption ?? 3) - 4) * 0.2);
  return v07ClampRating(avg - corruptionPenalty);
}

// Deterministically generate 10-stat ratings (REQ-08) whose computed quality matches targetQuality (1-10)
function generatePoliticianRatings(seedKey, targetQuality = 6, options = {}) {
  const target = v07ClampRating(targetQuality);
  const hBase = version01Hash(`ratings:${seedKey}`);
  const rawPos = V07_POSITIVE_RATING_KEYS.map((key, idx) => {
    const h = version01Hash(`${seedKey}:stat:${key}:${idx}`);
    const offset = ((h % 5) - 2); // -2 .. +2
    let v = v07ClampRating(target + offset);
    if (options.isIncumbent && key === 'experience') v = v07ClampRating(Math.max(v, target + 1));
    if (options.isRecruit && (key === 'persuadability' || key === 'charisma')) v = v07ClampRating(Math.max(v, target));
    return [key, v];
  });
  const ratings = Object.fromEntries(rawPos);
  const corrHash = version01Hash(`${seedKey}:stat:corruption`);
  ratings.corruption = options.corruption !== undefined
    ? v07ClampRating(options.corruption)
    : v07ClampRating(options.isRecruit ? 1 + (corrHash % 3) : 1 + (corrHash % 5));

  // Adjust positive ratings so v07ComputeQuality(ratings) === target when lockQuality is true
  if (options.lockQuality) {
    let safety = 0;
    while (v07ComputeQuality(ratings) !== target && safety < 36) {
      const current = v07ComputeQuality(ratings);
      const key = V07_POSITIVE_RATING_KEYS[(hBase + safety) % V07_POSITIVE_RATING_KEYS.length];
      if (current < target && ratings[key] < 10) {
        ratings[key] += 1;
      } else if (current > target && ratings[key] > 1) {
        ratings[key] -= 1;
      }
      safety += 1;
    }
  }
  return ratings;
}

