function getDecennialStatePopulations(year = 2030) {
  if (year === 2030) return { ...CENSUS_DECENNIAL_POPULATIONS_2030 };
  const base = { ...CENSUS_DECENNIAL_POPULATIONS_2030 };
  const step = Math.max(0, Math.floor((year - 2030) / 10));
  const sunbelt = ['TX', 'FL', 'AZ', 'NC', 'GA', 'SC', 'UT', 'NV', 'ID', 'TN', 'CO', 'WA'];
  const rustbelt = ['NY', 'IL', 'CA', 'PA', 'OH', 'MI', 'WV', 'LA'];
  const res = {};
  for (const [id, pop] of Object.entries(base)) {
    const rate = sunbelt.includes(id) ? 0.08 : rustbelt.includes(id) ? -0.015 : 0.025;
    res[id] = Math.round(pop * Math.pow(1 + rate, step));
  }
  return res;
}

function calculateDistrictPopulation(statePopulation, districtCount) {
  const n = Math.max(1, Number(districtCount) || 1);
  return Math.round(Number(statePopulation) / n);
}

function apportionHuntingtonHill(populations, totalSeats = 435) {
  const stateIds = Object.keys(populations).filter((id) => id !== 'DC');
  const seats = {};
  stateIds.forEach((id) => { seats[id] = 1; });
  let allocated = stateIds.length;

  while (allocated < totalSeats) {
    let maxPriority = -1;
    let chosenState = null;
    for (const id of stateIds) {
      const s = seats[id];
      const pop = Number(populations[id]) || 0;
      const priority = pop / Math.sqrt(s * (s + 1));
      if (priority > maxPriority) {
        maxPriority = priority;
        chosenState = id;
      }
    }
    if (!chosenState) break;
    seats[chosenState]++;
    allocated++;
  }
  return seats;
}

