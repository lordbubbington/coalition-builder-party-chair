function version043ApportionChapters(partyId, total = 800) {
  const isDemocratic = partyId === 'people';
  const rows = VERSION_01_STATES.map(state => {
    const lean = Math.max(-30, Math.min(30, state.lean)) / 30;
    const alignment = isDemocratic ? lean : -lean;
    const weight = VERSION_01_HOUSE_SEATS[state.id] * (1 + alignment * 0.5);
    return { stateId: state.id, weight };
  });
  const remaining = total - rows.length;
  const totalWeight = rows.reduce((sum, row) => sum + row.weight, 0);
  rows.forEach(row => {
    const quota = remaining * row.weight / totalWeight;
    row.count = 1 + Math.floor(quota);
    row.remainder = quota - Math.floor(quota);
  });
  let unassigned = total - rows.reduce((sum, row) => sum + row.count, 0);
  rows.slice().sort((a, b) => b.remainder - a.remainder || a.stateId.localeCompare(b.stateId))
    .slice(0, unassigned).forEach(row => { row.count += 1; });
  return Object.fromEntries(rows.map(row => [row.stateId, row.count]));
}
