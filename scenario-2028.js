function getSittingIncumbentForRace(raceId, partyId = null) {
  if (!raceId) return null;
  const direct = SITTING_MEMBERS.byRaceId?.[raceId];
  if (direct && (!partyId || direct.party === partyId)) return direct;
  if (raceId.startsWith('senate:')) {
    const stateId = raceId.split(':')[1];
    const sen = SITTING_MEMBERS.find((m) => m.office === 'senate' && m.stateId === stateId && m.senateClass === 3);
    if (sen && (!partyId || sen.party === partyId)) return sen;
  } else if (raceId.startsWith('governor:')) {
    const stateId = raceId.split(':')[1];
    const gov = SITTING_MEMBERS.find((m) => m.office === 'governor' && m.stateId === stateId);
    if (gov && (!partyId || gov.party === partyId)) return gov;
  } else if (raceId.startsWith('house:')) {
    const distId = raceId.split(':')[1];
    const rep = SITTING_MEMBERS.find((m) => m.office === 'house' && m.districtId === distId);
    if (rep && (!partyId || rep.party === partyId)) return rep;
  }
  return null;
}

function version01PrimaryField(raceId, stateName, partyId, seed = 1) {
  const sittingIncumbent = getSittingIncumbentForRace(raceId, partyId);
  const isMajorParty = ['people', 'heritage'].includes(partyId);

  // Small parties without a sitting incumbent do not have auto-generated candidates;
  // they can recruit candidates via the recruiting interface.
  if (!isMajorParty && !sittingIncumbent) {
    return [];
  }

  const wingsByParty = {
    people: ['Progressive', 'Moderate', 'Labor advocate', 'Local coalition'],
    heritage: ['MAGA populist', 'Moderate', 'Faith & community', 'Business conservative'],
    liberty: ['Classical Liberal', 'Civil Libertarian', 'Austrian School', 'Free Market Pragmatist'],
    green: ['Eco-Socialist', 'Grassroots Democracy', 'Municipalist', 'Clean Energy Advocate'],
    constitution: ['Faith & Flag', 'Strict Constitutionalist', 'Nationalist', 'Paleoconservative'],
    socialist: ['Democratic Socialist', 'Labor Radical', 'Syndicalist', 'Community Organizer'],
  };
  const wings = wingsByParty[partyId] || ['Grassroots Reformer', 'Independent Coalition', 'Local Advocate', 'Community Organizer'];
  const fieldHash = version01Hash(`${seed}:${raceId}:${partyId}`);
  const names = VERSION_01_RACE_CANDIDATE_NAMES;
  const strength = [34, 27, 13, 8];
  const stateCode = String(raceId || '').split(':')[1]?.split('-')[0] || '';
  const stateObj = STATE_BY_ID[stateCode] || VERSION_01_STATES.find((s) => s.name === stateName) || null;
  const stateRegions = stateObj?.regions || (stateObj?.region ? [stateObj.region] : ['South']);

  const candidateWings = isMajorParty ? wings : [sittingIncumbent?.wing || wings[0]];

  return candidateWings.map((wing, index) => {
    const h = version01Hash(`${fieldHash}:${index}`);
    const first = names.first[h % names.first.length];
    const last = names.last[(h >>> 8) % names.last.length];
    const isIncumbent = Boolean(index === 0 && sittingIncumbent);
    const candName = isIncumbent ? sittingIncumbent.name : `${first} ${last} (${raceId})`;
    const targetQuality = isIncumbent
      ? sittingIncumbent.quality
      : (index < 2 ? 6 + (h % 5) : 1 + (h % 8));
    const ratings = isIncumbent
      ? { ...sittingIncumbent.ratings }
      : generatePoliticianRatings(`${seed}:${raceId}:${partyId}:${index}`, targetQuality, { lockQuality: true });
    const quality = v07ComputeQuality(ratings);
    const fame = isIncumbent
      ? sittingIncumbent.fame
      : (10 + ((h >>> 4) % 36)); // REQ-10: non-incumbent primary candidates 10..45
    const happiness = isIncumbent ? sittingIncumbent.happiness : (65 + ((h >>> 10) % 20));
    const raw = {
      id: `${raceId}:${partyId}:${index}`,
      sittingMemberId: isIncumbent ? sittingIncumbent.id : null,
      name: candName,
      party: partyId,
      wing: isIncumbent ? (sittingIncumbent.wing || wing) : wing,
      stateId: stateObj?.id || stateCode || null,
      region: stateObj?.region || 'South',
      regions: stateRegions,
      ratings,
      quality,
      skill: Math.max(1, Math.min(5, Math.round(quality / 2))),
      fame,
      happiness,
      poll: strength[index] !== undefined ? (strength[index] + (h % 7) - 3 + (quality - 5) * 0.8 + (isIncumbent ? 10 : 0)) : (isIncumbent ? 65 : 25),
      endorsed: false,
      recruit: false,
      isIncumbent,
    };
    return (typeof window !== 'undefined' && window.PartyChairV07 && typeof window.PartyChairV07.normalizeCandidateRecord === 'function')
      ? window.PartyChairV07.normalizeCandidateRecord(raw, `${seed}:${raceId}:${partyId}:${index}`, quality)
      : raw;
  });
}

